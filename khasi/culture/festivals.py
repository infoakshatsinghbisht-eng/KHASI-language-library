def list_festivals() -> List[Dict[str, Any]]:
    """Return all documented traditional festivals of Khasi, Pnar, War, Bhoi, and Meghalaya heritage."""
    return KHASI_FESTIVALS

def get_festival(query: str) -> Optional[Dict[str, Any]]:
    """Find festival by name, location, or keyword."""
    q = query.lower().strip()
    for f in KHASI_FESTIVALS:
        if (q in f["name"].lower() or 
            q in f["description"].lower() or 
            q in f["month"].lower() or 
            q in f.get("location", "").lower() or
            q in f.get("tradition", "").lower()):
            return f
    return None
