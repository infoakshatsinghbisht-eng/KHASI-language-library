def get_author(name: str) -> Optional[Dict[str, Any]]:
    """Lookup author details by name (case-insensitive substring or token match)."""
    q = name.lower().strip()
    words = [w for w in q.split() if len(w) > 1]
    for a in AUTHORS:
        a_text = (a["name"] + " " + a.get("title", "")).lower()
        if q in a_text:
            return a
        if words and all(w in a_text for w in words):
            return a
    return None

def get_epic(title: str) -> Optional[Dict[str, Any]]:
    """Lookup epic or folk legend by title."""
    q = title.lower().strip()
    for e in EPICS:
        if q in e["title"].lower() or q in e["theme"].lower():
            return e
    return None

def search_literature(query: str) -> Dict[str, List[Dict[str, Any]]]:
    """Search authors, epics, and poems matching query."""
    q = query.lower().strip()
    return {
        "authors": [a for a in AUTHORS if q in a["name"].lower() or q in a["masterpiece"].lower() or q in a["biography"].lower()],
        "epics": [e for e in EPICS if q in e["title"].lower() or q in e["summary"].lower() or q in e["theme"].lower()],
        "poems": [p for p in POEMS if q in p["title"].lower() or q in p["poet"].lower() or q in p["text_khasi"].lower()]
    }
